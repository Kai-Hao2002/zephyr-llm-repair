# core/state.py
from typing import TypedDict, Annotated, List, Optional
import operator
from langchain_core.messages import AnyMessage

class ZephyrAgentState(TypedDict):
    """
    LangGraph 的全域狀態字典。
    代表一次除錯迴圈中，所有代理人共享的上下文與執行狀態。
    
    The global state dictionary for LangGraph.
    Represents the shared context and execution status across all agents in a debugging loop.
    """
    
    # === 1. 核心對話與日誌狀態 (Core Conversation & Log State) ===
    
    # 儲存所有 LLM 的對話歷史 (包含 System, Human, AI messages)
    # 使用 Annotated 與 operator.add 確保新訊息會被「附加」而非「覆寫」
    # Ensures new messages are appended to the list rather than overwriting it
    messages: Annotated[List[AnyMessage], operator.add]
    
    # 當前的錯誤日誌 (由 DevOps Expert 過濾後的精簡版本)
    # The current error log (compressed version from DevOps Expert)
    current_error_log: str
    
    # 錯誤類型 (例如: "build_error", "cmake_error", "qemu_crash", "success")
    # Error type categorization
    error_type: str
    
    # === 2. 領域知識與修補狀態 (Domain Knowledge & Patch State) ===
    
    # 知識專家 (Knowledge Expert) 決定要檢索的關鍵字
    # Keywords identified for graph retrieval
    search_keywords: List[str]
    
    # 從 Graph RAG 檢索出的硬體/軟體拓樸上下文
    # The topology context retrieved from Graph RAG
    retrieved_context: str
    
    # 修補專家 (Patch Expert) 產生的 SEARCH/REPLACE 區塊字串
    # The SEARCH/REPLACE block string generated by the Patch Expert
    patch_content: str

    # 上一次 ApplyPatch 節點實際成功套用到的檔案相對路徑列表——StaticCheck
    # 節點用它來決定要對哪些 .c 檔案跑 cppcheck (只檢查這次 patch 真的碰到
    # 的檔案，而不是整棵樹)。
    # Relative paths of files the last ApplyPatch node actually patched
    # successfully — the StaticCheck node uses this to decide which .c
    # files to run cppcheck against (only the files this patch actually
    # touched, not the whole tree).
    applied_files: List[str]

    # === 3. 系統控制與防呆機制 (System Control & Fail-safes) ===
    
    # 目標 Zephyr 專案的路徑
    # Path to the target Zephyr project
    workspace_path: str

    # 要建置的開發板 (例如 "qemu_x86"、"native_sim")。之前寫死在
    # devops_node 裡，現在改成從狀態讀取，這樣同一份 workflow 才能套用在
    # 資料集裡任何一個案例的目標板子上，而不是永遠只能建置 qemu_x86。
    # Target board to build for (e.g. "qemu_x86", "native_sim"). Previously
    # hardcoded inside devops_node; now read from state so the same
    # workflow can target whichever board a given dataset case actually
    # needs, instead of always building qemu_x86.
    board: str

    # 相對於 workspace_path 的目標 app 路徑 (例如
    # "tests/subsys/input/longpress")。demo 用途維持預設 "."
    # (workspace_path 本身就是 app 根目錄)。
    # Target app path relative to workspace_path (e.g.
    # "tests/subsys/input/longpress"). Defaults to "." for the demo case,
    # where workspace_path itself is the app root.
    target_app: str

    # 若這是在修復一個合成注入的 bug，這裡放該案例的 target_test (被注入
    # bug 打壞的那個 ztest 測試名稱)。DevOps Expert 會拿它去確認修復後的
    # patch 讓「這個特定測試」真的通過，而不只是看套件整體有沒有印出成功
    # 總結——避免投機的 patch (刪掉/跳過該測試) 被誤判為修復成功。
    # kconfig/dts/c_syntax 這類建置失敗的案例沒有對應的測試名稱，留 None。
    # If this is repairing a synthetic injected bug, this holds that case's
    # target_test (the ztest test name the injection broke). The DevOps
    # Expert uses it to confirm the repaired patch makes *that specific
    # test* actually pass, not just that the suite printed some success
    # summary — guarding against a shortcut patch (deleting/skipping that
    # test) being misclassified as a successful repair. None for build-
    # failure cases (kconfig/dts/c_syntax) that have no test name at all.
    required_pass_test: Optional[str]

    # 目前已經嘗試修復的迴圈次數
    # Current number of repair attempts
    iterations: int
    
    # 最大允許重試次數 (防止無限迴圈)
    # Maximum allowed retries to prevent infinite loops
    max_iterations: int
    
    # 當前整個系統的最終狀態 (例如: "in_progress", "resolved", "failed_max_retries")
    # Overall system status
    final_status: str

# ==========================================
# 輔助函數 (Helper Functions)
# ==========================================
def create_initial_state(workspace_path: str, initial_log: str, max_iters: int = 5,
                          board: str = "qemu_x86", target_app: str = ".",
                          required_pass_test: Optional[str] = None) -> ZephyrAgentState:
    """
    建立狀態機的初始狀態 (Initializes the state machine's state).

    :param board: 目標開發板，預設 "qemu_x86" 維持既有 demo 行為不變。
        Target board; defaults to "qemu_x86" to keep the existing demo's
        behavior unchanged.
    :param target_app: 相對於 workspace_path 的目標 app 路徑，預設 "."
        維持既有 demo 行為不變 (workspace_path 本身就是 app 根目錄)。
        Target app path relative to workspace_path; defaults to "." to
        keep the existing demo's behavior unchanged (workspace_path itself
        is the app root).
    :param required_pass_test: 若在修復資料集裡的一筆合成注入案例，帶入
        該案例的 target_test，讓 DevOps Expert 確認修復後那個特定測試真的
        通過，而不只是套件整體回報成功。
        If repairing a dataset's synthetic injected case, pass that case's
        target_test so the DevOps Expert confirms that specific test
        genuinely passes after the repair, not just that the suite as a
        whole reports success.
    """
    return {
        "messages": [],
        "current_error_log": initial_log,
        "error_type": "initial_build_error",
        "search_keywords": [],
        "retrieved_context": "",
        "patch_content": "",
        "applied_files": [],
        "workspace_path": workspace_path,
        "board": board,
        "target_app": target_app,
        "required_pass_test": required_pass_test,
        "iterations": 0,
        "max_iterations": max_iters,
        "final_status": "in_progress"
    }

# ==========================================
# 測試區塊 (Testing Block)
# ==========================================
if __name__ == "__main__":
    from langchain_core.messages import HumanMessage, AIMessage
    
    print("=== 初始化狀態 (Initializing State) ===")
    state = create_initial_state(
        workspace_path="/test/zephyr_project",
        initial_log="CMake Error at CMakeLists.txt:10",
        max_iters=3
    )
    print(f"專案路徑 (Workspace): {state['workspace_path']}")
    print(f"初始錯誤 (Initial Error): {state['current_error_log']}")
    print(f"目前迭代/最大上限 (Iterations): {state['iterations']} / {state['max_iterations']}")
    
    # 模擬 LangGraph 框架自動附加訊息的行為
    print("\n=== 模擬訊息附加 (Simulating Message Appending) ===")
    state["messages"] = operator.add(state["messages"], [HumanMessage(content="分析這個日誌")])
    state["messages"] = operator.add(state["messages"], [AIMessage(content="發現 CMake 錯誤，需要檢索 Kconfig。")])
    
    for msg in state["messages"]:
        print(f"[{type(msg).__name__}]: {msg.content}")