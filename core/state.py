# core/state.py
from typing import TypedDict, Annotated, List, Optional
import operator
from langchain_core.messages import AnyMessage

class ZephyrAgentState(TypedDict):
    """
    LangGraph 的全域狀態字典。
    代表一次除錯迴圈中，所有代理人共享的上下文與執行狀態。
    
    The global state dictionary for LangGraph.
    Represents the shared context and execution status across all agents in a debugging loop.
    """
    
    # === 1. 核心對話與日誌狀態 (Core Conversation & Log State) ===
    
    # 儲存所有 LLM 的對話歷史 (包含 System, Human, AI messages)
    # 使用 Annotated 與 operator.add 確保新訊息會被「附加」而非「覆寫」
    # Ensures new messages are appended to the list rather than overwriting it
    messages: Annotated[List[AnyMessage], operator.add]
    
    # 當前的錯誤日誌 (由 DevOps Expert 過濾後的精簡版本)
    # The current error log (compressed version from DevOps Expert)
    current_error_log: str
    
    # 錯誤類型 (例如: "build_error", "cmake_error", "qemu_crash", "success")
    # Error type categorization
    error_type: str
    
    # === 2. 領域知識與修補狀態 (Domain Knowledge & Patch State) ===
    
    # 知識專家 (Knowledge Expert) 決定要檢索的關鍵字
    # Keywords identified for graph retrieval
    search_keywords: List[str]
    
    # 從 Graph RAG 檢索出的硬體/軟體拓樸上下文
    # The topology context retrieved from Graph RAG
    retrieved_context: str

    # Hybrid RAG (BM25 + 語意 embedding，見 graph_rag/hybrid_retriever.py)
    # 額外檢索出的候選檔案相對路徑——補上 retrieved_context 那份圖遍歷
    # 檢索的結構性盲區：圖譜只認得 Kconfig 符號/DTS 節點名稱，答不出
    # 「哪個 C 檔案實作了這個子系統的邏輯」。Patch Expert 的
    # _collect_relevant_context_paths 會把這些路徑也納入候選。
    # Candidate file paths additionally retrieved by Hybrid RAG (BM25 +
    # semantic embedding, see graph_rag/hybrid_retriever.py) — closes a
    # structural blind spot in retrieved_context's graph-traversal
    # retrieval: the graph only recognizes Kconfig-symbol/DTS-node names,
    # with no way to answer "which C file implements this subsystem's
    # logic". Patch Expert's _collect_relevant_context_paths also includes
    # these paths among its candidates.
    retrieved_files: List[str]
    
    # 修補專家 (Patch Expert) 產生的 SEARCH/REPLACE 區塊字串
    # The SEARCH/REPLACE block string generated by the Patch Expert
    patch_content: str

    # 每次迭代嘗試過的修補與結果的精簡紀錄——Patch Expert 生成下一次修補
    # 之前會讀取這份歷史，避免在同一個已經證明無效的方向上重複打轉 (實測
    # 2026-08-30/31 的 runtime_crash/compound pilot 都出現這種現象：LLM
    # 反覆修改同一批看得到的檔案，卻從來不知道上一次的修改已經試過而且
    # 沒用)。用 Annotated + operator.add，跟 messages 同一種「附加而非
    # 覆寫」機制。第幾次迭代之後改成一句話壓縮摘要，見
    # agents/supervisor.py 的 CONTEXT_COMPRESSION_THRESHOLD_ITERATION。
    # A compressed record of each iteration's attempted patch and its
    # outcome — the Patch Expert reads this history before generating the
    # next patch, to avoid circling on a direction already shown not to
    # work (observed empirically in the 2026-08-30/31 runtime_crash/
    # compound pilots: the LLM kept re-editing the same visible files with
    # no memory that an earlier edit already tried and failed). Uses
    # Annotated + operator.add, the same "append, don't overwrite"
    # mechanism as messages. Compressed to a one-sentence summary from a
    # given iteration onward — see agents/supervisor.py's
    # CONTEXT_COMPRESSION_THRESHOLD_ITERATION.
    attempt_history: Annotated[List[str], operator.add]

    # 上一次 ApplyPatch 節點實際成功套用到的檔案相對路徑列表——StaticCheck
    # 節點用它來決定要對哪些 .c 檔案跑 cppcheck (只檢查這次 patch 真的碰到
    # 的檔案，而不是整棵樹)。
    # Relative paths of files the last ApplyPatch node actually patched
    # successfully — the StaticCheck node uses this to decide which .c
    # files to run cppcheck against (only the files this patch actually
    # touched, not the whole tree).
    applied_files: List[str]

    # === 4. 評分指標蒐集 (Metrics Collection，見 evaluate.py/analyze_results.py) ===

    # 每次迭代結束時 (跟 attempt_history 完全同一組寫入點，見
    # agents/supervisor.py 的 record_attempt_outcome/record_iteration_success)
    # 附加一筆紀錄：這次迭代有沒有真的編譯出執行檔 (compiled)、有沒有修復
    # 成功 (resolved)、patch 格式本身是否有效 (tool_invocation_error)，以及
    # 這次迭代所有 LLM 呼叫的 token 用量。用 Annotated + operator.add，跟
    # attempt_history 同一種「附加而非覆寫」機制。RQ1/RQ3 的 Pass@k /
    # Functional Pass Rate / 迭代次數、RQ4 的 Token Efficiency，都從這裡
    # 算，不在別處另外重算一次容易漂移的邏輯。
    # One entry appended at the end of each iteration (exactly the same
    # write points as attempt_history — see agents/supervisor.py's
    # record_attempt_outcome/record_iteration_success): whether this
    # iteration actually produced a compiled binary (compiled), whether it
    # resolved the case (resolved), whether the patch itself was validly
    # formatted (tool_invocation_error), and the token usage of every LLM
    # call made during this iteration. Annotated + operator.add, the same
    # "append, don't overwrite" mechanism as attempt_history. RQ1/RQ3's
    # Pass@k / Functional Pass Rate / iteration count and RQ4's Token
    # Efficiency are all computed from this, not re-derived elsewhere.
    iteration_log: Annotated[List[dict], operator.add]

    # 這次迭代目前已知、但還沒寫進 iteration_log 的 LLM token 用量——
    # Analyzer/Patch/Supervisor 壓縮呼叫都各自把自己那次呼叫的用量附加進
    # 這裡，等這次迭代結束時 (寫 iteration_log 那一刻) 一次讀出、歸零，
    # 讓下一次迭代重新累積。不是 Annotated：讀出並整份覆寫回去是這個欄位
    # 本來就設計成的用法 (跟 attempt_history/iteration_log 的「只附加」
    # 語意不同)。
    # Token usage known so far this iteration but not yet flushed into
    # iteration_log — Analyzer/Patch/Supervisor's compression call each
    # append their own call's usage here; read out and reset to [] exactly
    # when this iteration's iteration_log entry gets written, so the next
    # iteration starts accumulating fresh. Not Annotated: read-then-
    # overwrite-in-full is the intended usage here (different "append-only"
    # semantics from attempt_history/iteration_log).
    pending_token_usage: List[dict]

    # 只在 Knowledge Expert「第一次」真正執行檢索時寫入，之後永遠不再覆蓋
    # (見 agents/knowledge_expert.py)。RQ2 的 MRR/Recall@k/Top-k Accuracy
    # 依使用者確認的方法論，只看第一次診斷觸發的檢索結果，不算閉環重試
    # 帶來的效果 (那是 RQ3 的事)——None 代表這次案例從頭到尾都沒有觸發過
    # 檢索 (例如 B1/B3 完全沒有 RAG，或 Proposed/B2 從沒被 Analyzer 判定
    # 需要檢索)。
    # Written only the "first" time Knowledge Expert actually performs a
    # retrieval, never overwritten after (see agents/knowledge_expert.py).
    # Per the confirmed methodology, RQ2's MRR/Recall@k/Top-k Accuracy only
    # look at the first diagnosis's retrieval result, not whatever benefit
    # closed-loop retries add (that's RQ3's concern). None means retrieval
    # never fired at all for this case (e.g. B1/B3 have no RAG at all, or
    # Proposed/B2 never had Analyzer decide retrieval was needed).
    first_retrieval_files: Optional[List[str]]

    # === 3. 系統控制與防呆機制 (System Control & Fail-safes) ===
    
    # 目標 Zephyr 專案的路徑
    # Path to the target Zephyr project
    workspace_path: str

    # 要建置的開發板 (例如 "qemu_x86"、"native_sim")。之前寫死在
    # devops_node 裡，現在改成從狀態讀取，這樣同一份 workflow 才能套用在
    # 資料集裡任何一個案例的目標板子上，而不是永遠只能建置 qemu_x86。
    # Target board to build for (e.g. "qemu_x86", "native_sim"). Previously
    # hardcoded inside devops_node; now read from state so the same
    # workflow can target whichever board a given dataset case actually
    # needs, instead of always building qemu_x86.
    board: str

    # 相對於 workspace_path 的目標 app 路徑 (例如
    # "tests/subsys/input/longpress")。demo 用途維持預設 "."
    # (workspace_path 本身就是 app 根目錄)。
    # Target app path relative to workspace_path (e.g.
    # "tests/subsys/input/longpress"). Defaults to "." for the demo case,
    # where workspace_path itself is the app root.
    target_app: str

    # 若這是在修復一個合成注入的 bug，這裡放該案例的 target_test (被注入
    # bug 打壞的那個 ztest 測試名稱)。DevOps Expert 會拿它去確認修復後的
    # patch 讓「這個特定測試」真的通過，而不只是看套件整體有沒有印出成功
    # 總結——避免投機的 patch (刪掉/跳過該測試) 被誤判為修復成功。
    # kconfig/dts/c_syntax 這類建置失敗的案例沒有對應的測試名稱，留 None。
    # If this is repairing a synthetic injected bug, this holds that case's
    # target_test (the ztest test name the injection broke). The DevOps
    # Expert uses it to confirm the repaired patch makes *that specific
    # test* actually pass, not just that the suite printed some success
    # summary — guarding against a shortcut patch (deleting/skipping that
    # test) being misclassified as a successful repair. None for build-
    # failure cases (kconfig/dts/c_syntax) that have no test name at all.
    required_pass_test: Optional[str]

    # 目前已經嘗試修復的迴圈次數
    # Current number of repair attempts
    iterations: int
    
    # 最大允許重試次數 (防止無限迴圈)
    # Maximum allowed retries to prevent infinite loops
    max_iterations: int
    
    # 當前整個系統的最終狀態 (例如: "in_progress", "resolved", "failed_max_retries")
    # Overall system status
    final_status: str

# ==========================================
# 輔助函數 (Helper Functions)
# ==========================================
def create_initial_state(workspace_path: str, initial_log: str, max_iters: int = 5,
                          board: str = "qemu_x86", target_app: str = ".",
                          required_pass_test: Optional[str] = None) -> ZephyrAgentState:
    """
    建立狀態機的初始狀態 (Initializes the state machine's state).

    :param board: 目標開發板，預設 "qemu_x86" 維持既有 demo 行為不變。
        Target board; defaults to "qemu_x86" to keep the existing demo's
        behavior unchanged.
    :param target_app: 相對於 workspace_path 的目標 app 路徑，預設 "."
        維持既有 demo 行為不變 (workspace_path 本身就是 app 根目錄)。
        Target app path relative to workspace_path; defaults to "." to
        keep the existing demo's behavior unchanged (workspace_path itself
        is the app root).
    :param required_pass_test: 若在修復資料集裡的一筆合成注入案例，帶入
        該案例的 target_test，讓 DevOps Expert 確認修復後那個特定測試真的
        通過，而不只是套件整體回報成功。
        If repairing a dataset's synthetic injected case, pass that case's
        target_test so the DevOps Expert confirms that specific test
        genuinely passes after the repair, not just that the suite as a
        whole reports success.
    """
    return {
        "messages": [],
        "current_error_log": initial_log,
        "error_type": "initial_build_error",
        "search_keywords": [],
        "retrieved_context": "",
        "retrieved_files": [],
        "patch_content": "",
        "attempt_history": [],
        "applied_files": [],
        "iteration_log": [],
        "pending_token_usage": [],
        "first_retrieval_files": None,
        "workspace_path": workspace_path,
        "board": board,
        "target_app": target_app,
        "required_pass_test": required_pass_test,
        "iterations": 0,
        "max_iterations": max_iters,
        "final_status": "in_progress"
    }

# ==========================================
# 測試區塊 (Testing Block)
# ==========================================
if __name__ == "__main__":
    from langchain_core.messages import HumanMessage, AIMessage
    
    print("=== 初始化狀態 (Initializing State) ===")
    state = create_initial_state(
        workspace_path="/test/zephyr_project",
        initial_log="CMake Error at CMakeLists.txt:10",
        max_iters=3
    )
    print(f"專案路徑 (Workspace): {state['workspace_path']}")
    print(f"初始錯誤 (Initial Error): {state['current_error_log']}")
    print(f"目前迭代/最大上限 (Iterations): {state['iterations']} / {state['max_iterations']}")
    
    # 模擬 LangGraph 框架自動附加訊息的行為
    print("\n=== 模擬訊息附加 (Simulating Message Appending) ===")
    state["messages"] = operator.add(state["messages"], [HumanMessage(content="分析這個日誌")])
    state["messages"] = operator.add(state["messages"], [AIMessage(content="發現 CMake 錯誤，需要檢索 Kconfig。")])
    
    for msg in state["messages"]:
        print(f"[{type(msg).__name__}]: {msg.content}")